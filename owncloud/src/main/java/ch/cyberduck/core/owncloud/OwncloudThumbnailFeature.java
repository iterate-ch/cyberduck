import ch.cyberduck.core.Path;
import ch.cyberduck.core.dav.DAVPathEncoder;
import ch.cyberduck.core.exception.BackgroundException;
import ch.cyberduck.core.exception.NotfoundException;
import ch.cyberduck.core.features.Thumbnail;
import ch.cyberduck.core.http.DefaultHttpResponseExceptionMappingService;
import ch.cyberduck.core.http.HttpExceptionMappingService;

import org.apache.http.HttpStatus;
import org.apache.http.client.HttpResponseException;
import org.apache.http.client.methods.HttpGet;
import org.apache.http.util.EntityUtils;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;

/**
 * Retrieve a preview image generated by the webdav service by requesting the file with the <code>preview</code>
 * query parameter.
 *
 * @see <a href="https://docs.opencloud.eu/docs/next/admin/maintenance/upgrade/upgrade-9.x.x/">OpenCloud 9.x upgrade</a>
 */
public class OwncloudThumbnailFeature implements Thumbnail {
    private static final Logger log = LogManager.getLogger(OwncloudThumbnailFeature.class);

    /**
     * Not part of the HTTP status constants of the client library
     */
    private static final int SC_TOO_EARLY = 425;

    /**
     * Maximum edge length of a preview accepted by the server
     */
    protected static final int MAXIMUM = 2048;

    private final OwncloudSession session;

    public OwncloudThumbnailFeature(final OwncloudSession session) {
        this.session = session;
    }

    @Override
    public InputStream thumbnail(final Path file, final int size) throws BackgroundException {
        try {
            final int dimension = toDimension(size);
            final HttpGet request = new HttpGet(String.format("%s?preview=1&x=%d&y=%d",
                    new DAVPathEncoder(session).encode(file), dimension, dimension));
            // Previews are small and the response is released by the client when the handler returns
            return new ByteArrayInputStream(session.getClient().execute(request, response -> {
                final int code = response.getStatusLine().getStatusCode();
                if(code == HttpStatus.SC_OK) {
                    return EntityUtils.toByteArray(response.getEntity());
                }
                EntityUtils.consumeQuietly(response.getEntity());
                throw new HttpResponseException(code, response.getStatusLine().getReasonPhrase());
            }));
        }
        catch(HttpResponseException e) {
            if(e.getStatusCode() == SC_TOO_EARLY) {
                // File is still being processed by the server and will have a preview later
                log.warn("No thumbnail available yet for file {}", file);
                throw new NotfoundException(file.getAbsolute(), e);
            }
            throw new DefaultHttpResponseExceptionMappingService().map("Download {0} failed", e, file);
        }
        catch(IOException e) {
            throw new HttpExceptionMappingService().map("Download {0} failed", e, file);
        }
    }

    /**
     * @return Requested size clamped to the range supported by the server
     */
    protected static int toDimension(final int size) {
        return Math.max(1, Math.min(size, MAXIMUM));
    }
}
